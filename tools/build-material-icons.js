// Dev-time tool: converts Material Symbols (Apache-2.0, Google) SVGs into
// js/icons-material.js in the app's 24-unit icon format.
//
// Usage:
//   node tools/build-material-icons.js <dir-with-svg-200> <dir-with-svg-300> <dir-with-svg-500>
// where each dir is the "rounded" folder of @material-symbols/svg-<weight>@0.48.0.
//
// For every icon we keep the outline path for three weights (light/regular/bold)
// and the filled silhouette (regular weight) that becomes the colour layer.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePath, transformSegments, segmentsToD } from '../js/path.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const MATERIAL_NAMES = [
  'lightbulb', 'light', 'wall_lamp', 'sunny', 'switch',
  'power', 'electric_bolt', 'electric_meter', 'ev_station', 'solar_power',
  'local_laundry_service', 'kitchen', 'oven_gen', 'dishwasher_gen', 'microwave_gen', 'range_hood',
  'water_heater', 'tv', 'water_pump', 'kettle', 'iron',
  'thermostat', 'heat', 'local_fire_department', 'mode_fan', 'water_drop', 'ac_unit', 'heat_pump',
  'wifi', 'router', 'lan', 'videocam', 'doorbell',
  'home', 'bed', 'weekend', 'bathtub', 'shower', 'child_care', 'yard', 'garage',
  'warning', 'block', 'lock', 'info', 'dangerous',
];

const [d200, d300, d500] = process.argv.slice(2);
if (!d500) {
  console.error('usage: node tools/build-material-icons.js <svg-200/rounded> <svg-300/rounded> <svg-500/rounded>');
  process.exit(1);
}

// Material viewBox is "0 -960 960 960"; map it onto 0..24.
const toGrid = (d) => segmentsToD(transformSegments(parsePath(d), (x, y) => [x / 40, (y + 960) / 40]), 2);
const pathsOf = async (file) => [...(await readFile(file, 'utf8')).matchAll(/<path d="([^"]+)"/g)].map((m) => toGrid(m[1]));

// Material icons keep generous internal padding. To match the visual size of the
// app's own icons, each icon is scaled (all weights by the same factor) so the
// regular-weight artwork spans TARGET units, centred on the 24-unit grid.
const TARGET = 19.5;
const bbox = (ds) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const d of ds) for (const s of parsePath(d)) for (const [x, y] of [[s.x, s.y], [s.x1, s.y1], [s.x2, s.y2]]) {
    if (x === undefined) continue;
    x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
  }
  return { x0, y0, x1, y1 };
};
const fit = (ds, b) => {
  const k = TARGET / Math.max(b.x1 - b.x0, b.y1 - b.y0);
  const cx = (b.x0 + b.x1) / 2, cy = (b.y0 + b.y1) / 2;
  return ds.map((d) => segmentsToD(transformSegments(parsePath(d), (x, y) => [12 + (x - cx) * k, 12 + (y - cy) * k]), 2));
};

const out = {};
for (const name of MATERIAL_NAMES) {
  const raw = {
    fill: await pathsOf(path.join(d300, `${name}-fill.svg`)),
    light: await pathsOf(path.join(d200, `${name}.svg`)),
    regular: await pathsOf(path.join(d300, `${name}.svg`)),
    bold: await pathsOf(path.join(d500, `${name}.svg`)),
  };
  const b = bbox([...raw.regular, ...raw.fill]);
  out[name] = Object.fromEntries(Object.entries(raw).map(([k, ds]) => [k, fit(ds, b)]));
}

const header = `// Generated by tools/build-material-icons.js. Do not edit by hand.
// Icons: Material Symbols (Rounded), © Google, Apache License 2.0
// (see assets/icons/LICENSE-material-symbols.txt). Coordinates are on a 24-unit grid.
`;
await writeFile(path.join(ROOT, 'js/icons-material.js'), `${header}export const MATERIAL = ${JSON.stringify(out)};\n`);
console.log(`${MATERIAL_NAMES.length} icons written`);
